const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const source=fs.readFileSync(path.join(__dirname,'../src/Prognode.Host/wwwroot/app.js'),'utf8');
const start=source.indexOf('function modbusAddressInfo('),end=source.indexOf('function describeTagAddress(',start);
assert(start>=0&&end>start);
const state={editingTagId:null,tags:[]},context={state,Number,String};
vm.createContext(context);vm.runInContext(source.slice(start,end),context);
const tag=(id,deviceId,address,dataType='UInt16')=>({id,deviceId,address,dataType});
assert.equal(context.nextModbusTagAddress('d1','UInt16'),'40001');
state.tags=[tag('a','d1','40001'),tag('b','d1','40002')];
assert.equal(context.nextModbusTagAddress('d1','UInt16'),'40003');
state.tags=[tag('a','d1','40001','Float32'),tag('other','d2','40003')];
assert.equal(context.nextModbusTagAddress('d1','UInt16'),'40003','32-bit register span and other device');
state.tags=[tag('a','d1','40004')];
assert.equal(context.nextModbusTagAddress('d1','Float32'),'40001');
state.tags=[tag('a','d1','40001'),tag('b','d1','40004')];
assert.equal(context.nextModbusTagAddress('d1','Float32'),'40002','two-register candidate fits before 40004');
state.tags=[tag('a','d1','00001','Bool'),tag('b','d1','00002','Bool')];
assert.equal(context.nextModbusTagAddress('d1','Bool'),'00003');
assert.equal(context.nextModbusTagAddress('d1','Word'),'40001','coil addresses do not occupy holding registers');
state.tags=[tag('a','d1','40001')];state.editingTagId='a';
assert.equal(context.nextModbusTagAddress('d1','UInt16'),'40001','editing ignores its own address');
console.log('PASS: Modbus next free address respects device, area and 32-bit width');
