const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.join(__dirname,'../src');
const app=fs.readFileSync(path.join(root,'Prognode.Host/wwwroot/app.js'),'utf8');
const agent=fs.readFileSync(path.join(root,'Prognode.Agent.Windows/AgentApplicationContext.cs'),'utf8');
const begin=app.indexOf('function openAlarmFromNotification()');
const end=app.indexOf('function limitText(',begin);
assert(begin>=0&&end>begin);
let opened='',scrolled=false;
const context={navigate:page=>opened=page,document:{getElementById:id=>id==='page-alarms'?{scrollIntoView:()=>scrolled=true}:null}};
vm.createContext(context);vm.runInContext(app.slice(begin,end),context);
context.openAlarmFromNotification();
assert.equal(opened,'alarms');assert(scrolled);
assert(app.includes('data-open-notification-alarm='),'notification rows must be clickable');
assert(app.includes("window.location.hash.replace(/^#/,'').split('?')[0]==='alarms'"),'deep link must restore alarm page');
assert(agent.includes('new WindowsNotificationService(OpenAlarms)'),'Windows toast activation must open alarms');
assert(agent.includes('BalloonTipClicked += (_, _) => OpenAlarms()'),'tray fallback activation must open alarms');
assert(agent.includes('"/#alarms"'),'Agent must launch alarm deep link');
console.log('PASS: notification center, overview and Windows activation navigate to alarms');
