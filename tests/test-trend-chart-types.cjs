const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const source=fs.readFileSync(path.join(__dirname,'../src/Prognode.Host/wwwroot/trend-hf3plus.js'),'utf8');
const helperStart=source.indexOf('function monotonePath(');
const helperEnd=source.indexOf('function qualityWindows(',helperStart);
const typeStart=source.indexOf('function trendStrokePath(');
const typeEnd=source.indexOf('function drawChartNow(',typeStart);
assert(helperStart>=0&&helperEnd>helperStart&&typeStart>=0&&typeEnd>typeStart);
const context={};vm.createContext(context);
vm.runInContext(source.slice(helperStart,helperEnd)+source.slice(typeStart,typeEnd),context);
const points=[{t:0,v:2},{t:10,v:5},{t:20,v:3}],x=t=>t,y=v=>10-v;
const line=context.trendStrokePath({chartType:'line'},points,x,y);
const smooth=context.trendStrokePath({chartType:'smooth'},points,x,y);
const area=context.trendAreaPath({chartType:'area'},points,x,y,20);
assert(line.includes(' L ')&&!line.includes(' C '),'line must use straight segments');
assert(smooth.includes(' C '),'smooth must use curved segments');
assert(area.includes(' C ')&&area.endsWith(' Z')&&area.includes('20.00'),'area must be a closed shaded curve');
assert.equal(context.trendAreaPath({chartType:'line'},points,x,y,20),null);
assert(source.includes("c.chartType=['line','smooth','area'].includes(x.chartType)"),'saved chart type must restore');
assert(source.includes('chartType:c.chartType'),'chart type must persist in layout');
assert(source.includes('data-chart-type='),'chart type must be selectable per panel');
console.log('PASS: straight, smooth and shaded trend types with saved per-panel choice');
